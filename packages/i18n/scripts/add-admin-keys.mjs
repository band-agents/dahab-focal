/**
 * Values that are legitimately identical to en-GB: the console's proper name,
 * and column headers that are the same word in that language. Declared so the
 * identical-value check stays meaningful.
 */
const IDENTICAL = {
  'de-DE': ['admin.console', 'admin.col.status'],
  'it-IT': ['admin.console'],
  'fr-FR': [
    'admin.console',
    'admin.col.document',
    'admin.col.site',
    'admin.nav.catalog',
    // "document" is the same word in French, so the plural message is too.
    'admin.expiry.count',
  ],
  'es-ES': ['admin.console'],
};

for (const [locale, block] of Object.entries(ADMIN)) {
  const path = resolve(messagesDir, `${locale}.json`);
  const catalogue = JSON.parse(readFileSync(path, 'utf8'));
  catalogue.admin = block;

  const declared = IDENTICAL[locale];
  if (declared !== undefined) {
    const existing = catalogue.$meta.identicalToSource ?? [];
    catalogue.$meta.identicalToSource = [...new Set([...existing, ...declared])].sort();
  }

  writeFileSync(path, `${JSON.stringify(catalogue, null, 2)}\n`);
  console.log(`admin keys → ${locale}`);
}
